"""SQL-to-question benchmark construction, scoring, and paired A/B statistics.

Benchmark example i = (q_i, D, r_i*), where
    SQL_i*  reference query (written by hand below)
    q_i     natural-language question generated by an LLM from SQL_i*
    r_i*    Execute(SQL_i*, D)
"""
